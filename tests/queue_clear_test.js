const assert = require('node:assert/strict');
const queueModule = require('../assets/js/device-queue.js');
let data = [], fail = false, changes = [];
const q = queueModule.create({read:()=>data,write:(items)=>{ if(fail)return false; data=items; return true; }});
q.onChange(n=>changes.push(n));
q.push({local_event_id:'event-1',employee_id:1});
q.push({local_event_id:'event-2',employee_id:1});
q.applyResults([{local_event_id:'event-1',status:'DUPLICATE'},{local_event_id:'event-2',status:'REJECTED'}]);
assert.deepEqual(data.map(x=>x.local_event_id),['event-2']);
fail=true; assert.equal(q.clearQueue(),false); assert.equal(data.length,1);
fail=false; assert.equal(q.clearQueue(),true); assert.equal(data.length,0); assert.equal(changes.at(-1),0);
console.log('Queue duplicate removal, refused retention and confirmed clear persistence OK');
